
import type { IdleMode, WorldWeather } from '@/types/world'
import { seededWorldRoll } from './worldSeed'

export interface NarrativeContext {
  realm: string
  weather: WorldWeather
  mode: IdleMode
  totalTicks: number
}

export type NarrativeCategory = 
  | 'cultivation' | 'adventure' | 'herb' | 'sect_duty' | 'skill_train'
  | 'npc_interaction' | 'world_event'

export function pickNarrative(
  category: NarrativeCategory,
  context: NarrativeContext,
  variant: number = 0
): string {
  const texts = NARRATIVE_TEXTS[category]
  if (!texts || texts.length === 0) return ''
  const idx = Math.floor(
    seededWorldRoll(context.totalTicks, category, String(variant)) * texts.length
  ) % texts.length
  return texts[idx] ?? ''
}

